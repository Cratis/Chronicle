using System.Text;

namespace Cratis.Chronicle.Tools.GrpcCodeGenerator;

/// <summary>
/// Generates the composition root entry that registers and maps every generated gRPC service.
/// </summary>
/// <param name="targetNamespace">The namespace to place the generated registrations in.</param>
/// <remarks>
/// The generator already knows every service it produced, so deriving the registrations removes the one manual
/// step migrating an area would otherwise still need - and the one that fails silently, since a service nobody
/// registered is simply absent at runtime rather than a compile error.
/// </remarks>
public class ServiceRegistrationsGenerator(string targetNamespace)
{
    const string Header =
        "// Copyright (c) Cratis. All rights reserved.\n" +
        "// Licensed under the MIT license. See LICENSE file in the project root for full license information.\n\n" +
        "// <auto-generated />\n\n" +
        "#nullable enable\n\n";

    /// <summary>
    /// Generates the registrations file.
    /// </summary>
    /// <param name="services">The services that were generated.</param>
    /// <param name="outputPath">The file to write.</param>
    public void Generate(IEnumerable<GeneratedService> services, string outputPath)
    {
        var ordered = services.OrderBy(_ => _.TypeName, StringComparer.Ordinal).ToList();

        var builder = new StringBuilder(Header);
        builder.AppendLine("using Microsoft.AspNetCore.Builder;");
        builder.AppendLine("using Microsoft.AspNetCore.Routing;");
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine();
        builder.AppendLine($"namespace {targetNamespace};");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Registers the gRPC services generated from the Arc artifacts in Core.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("internal static class GeneratedGrpcServices");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Adds every generated gRPC service implementation.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    /// <param name=\"services\">The service collection to add to.</param>");
        builder.AppendLine("    /// <returns>The service collection for continuation.</returns>");
        builder.AppendLine("    internal static IServiceCollection AddGeneratedGrpcServices(this IServiceCollection services)");
        builder.AppendLine("    {");
        foreach (var service in ordered)
        {
            builder.AppendLine($"        services.AddSingleton<{service.ContractTypeName}, {service.TypeName}>();");
        }

        builder.AppendLine();
        builder.AppendLine("        return services;");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Maps every generated gRPC service onto the endpoints.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    /// <param name=\"endpoints\">The endpoint route builder to map onto.</param>");
        builder.AppendLine("    /// <returns>The endpoint route builder for continuation.</returns>");
        builder.AppendLine("    internal static IEndpointRouteBuilder MapGeneratedGrpcServices(this IEndpointRouteBuilder endpoints)");
        builder.AppendLine("    {");
        foreach (var service in ordered)
        {
            builder.AppendLine($"        endpoints.MapGrpcService<{service.TypeName}>();");
        }

        builder.AppendLine();
        builder.AppendLine("        return endpoints;");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
        File.WriteAllText(outputPath, builder.ToString());
    }
}
