using System.Globalization;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Cratis.Chronicle.Tools.GrainCompatibility.Payloads;

/// <summary>
/// The serialized shapes of grain-call arguments and results in one build.
/// </summary>
/// <param name="Types">The payload types, keyed by wire identity.</param>
public partial record PayloadContractManifest(IReadOnlyDictionary<string, PayloadTypeContract> Types)
{
    const int MatchTimeoutMilliseconds = 1000;

    [GeneratedRegex("""^(?<kind>json|orleans|concept|enum|oneof|custom) (?:\[Alias\((?<alias>"(?:[^"\\]|\\.)*")\)\] )?(?<name>\S+)(?: : (?<underlying>\S+))?$""", RegexOptions.None, MatchTimeoutMilliseconds)]
    static partial Regex TypeLine { get; }

    [GeneratedRegex(@"^(?:\[Id\((?<id>\d+)\)\] )?(?<name>\S+): (?<type>\S+)$", RegexOptions.None, MatchTimeoutMilliseconds)]
    static partial Regex MemberLine { get; }

    [GeneratedRegex(@"^(?<name>\S+) = (?<value>-?\d+)$", RegexOptions.None, MatchTimeoutMilliseconds)]
    static partial Regex EnumLine { get; }

    /// <summary>
    /// Reads the text of a payload snapshot.
    /// </summary>
    /// <param name="text">The manifest text.</param>
    /// <returns>The parsed manifest.</returns>
    /// <exception cref="InvalidPayloadContractManifest">Thrown when a declaration cannot be read.</exception>
    public static PayloadContractManifest Parse(string text)
    {
        var types = new Dictionary<string, PayloadTypeContract>(StringComparer.Ordinal);
        PayloadTypeContract? current = null;
        List<PayloadMemberContract>? members = null;
        var lines = text.ReplaceLineEndings("\n").Split('\n');

        for (var index = 0; index < lines.Length; index++)
        {
            var line = lines[index].TrimEnd();
            var lineNumber = index + 1;
            if (line.Length == 0 || line.StartsWith('#'))
            {
                continue;
            }

            if (line.StartsWith("  ", StringComparison.Ordinal))
            {
                AddMember(current, members, line[2..], lineNumber);
                continue;
            }

            members = [];
            current = ParseType(line, lineNumber, members);
            if (!types.TryAdd(current.Identity, current))
            {
                throw new InvalidPayloadContractManifest(lineNumber, $"Type '{current.Identity}' is declared twice.");
            }
        }

        return new(types);
    }

    /// <summary>
    /// Writes the deterministic, version 1 snapshot format.
    /// </summary>
    /// <returns>The manifest text, sorted by identity and serialized member name or ID.</returns>
    public string ToText()
    {
        var lines = new List<string>
        {
            "# Grain payload contracts format: 1",
            "# Generated by the GrainCompatibility specs from Source/Kernel/Core. Do not hand-edit.",
            "# Every type reachable from an active grain interface method in OrleansContracts.txt, as its codec writes it.",
            "# On drift the specs write GrainPayloadContracts.received.txt next to the spec assembly: copy it here and review the diff."
        };

        foreach (var type in Types.Values.OrderBy(_ => _.Identity, StringComparer.Ordinal))
        {
            var alias = type.Alias is null ? string.Empty : $"[Alias({JsonSerializer.Serialize(type.Alias)})] ";
            var underlying = type.Underlying is null ? string.Empty : $" : {type.Underlying}";
            lines.Add($"{type.Kind.ToString().ToLowerInvariant()} {alias}{type.ClrName}{underlying}");
            lines.AddRange(type.Members.OrderBy(_ => _.Id).ThenBy(_ => _.Name, StringComparer.Ordinal).Select(_ => MemberText(type.Kind, _)));
        }

        return string.Join('\n', lines) + "\n";
    }

    static PayloadTypeContract ParseType(string line, int lineNumber, List<PayloadMemberContract> members)
    {
        var match = TypeLine.Match(line);
        if (!match.Success)
        {
            throw new InvalidPayloadContractManifest(lineNumber, $"Not a type or member declaration: '{line}'.");
        }

        var kind = Enum.Parse<PayloadKind>(match.Groups["kind"].Value, ignoreCase: true);
        var underlying = match.Groups["underlying"].Success ? match.Groups["underlying"].Value : null;
        var hasAlias = match.Groups["alias"].Success;
        var requiresUnderlying = kind is PayloadKind.Concept or PayloadKind.Enum;
        var hasUnexpectedUnderlying = (underlying is not null) != requiresUnderlying;
        var hasUnexpectedAlias = hasAlias && kind != PayloadKind.Orleans;
        if (hasUnexpectedUnderlying || hasUnexpectedAlias)
        {
            throw new InvalidPayloadContractManifest(lineNumber, $"Invalid alias or underlying type for {kind}.");
        }

        var alias = hasAlias ? ParseAlias(match.Groups["alias"].Value, lineNumber) : null;
        var name = match.Groups["name"].Value;
        return new(alias ?? name, name, kind, alias, underlying, members);
    }

    static string? ParseAlias(string text, int lineNumber)
    {
        try
        {
            return JsonSerializer.Deserialize<string>(text);
        }
        catch (JsonException)
        {
            throw new InvalidPayloadContractManifest(lineNumber, "Invalid escaped alias.");
        }
    }

    static void AddMember(PayloadTypeContract? current, List<PayloadMemberContract>? members, string line, int lineNumber)
    {
        if (current is null || members is null)
        {
            throw new InvalidPayloadContractManifest(lineNumber, "A member appears before any type.");
        }

        var member = ParseMember(current.Kind, line, lineNumber);
        var duplicateName = members.Exists(_ => _.Name == member.Name);
        var duplicateId = member.Id is not null && members.Exists(_ => _.Id == member.Id);
        if (duplicateName || duplicateId)
        {
            throw new InvalidPayloadContractManifest(lineNumber, $"Member '{member.Name}' or its ID appears twice on {current.ClrName}.");
        }

        members.Add(member);
    }

    static PayloadMemberContract ParseMember(PayloadKind kind, string line, int lineNumber)
    {
        if (kind == PayloadKind.Enum && EnumLine.Match(line) is { Success: true } enumMatch)
        {
            return new(enumMatch.Groups["name"].Value, enumMatch.Groups["value"].Value);
        }

        var match = MemberLine.Match(line);
        var hasId = match.Groups["id"].Success;
        var forbidsMembers = kind is PayloadKind.Concept or PayloadKind.Custom or PayloadKind.Enum;
        var invalidId = hasId != (kind == PayloadKind.Orleans);
        if (forbidsMembers || !match.Success || invalidId)
        {
            throw new InvalidPayloadContractManifest(lineNumber, $"Invalid {kind} member: '{line}'.");
        }

        int? id = null;
        if (hasId)
        {
            if (!int.TryParse(match.Groups["id"].Value, NumberStyles.None, CultureInfo.InvariantCulture, out var value))
            {
                throw new InvalidPayloadContractManifest(lineNumber, "Serializer ID is outside the supported range.");
            }

            id = value;
        }

        return new(match.Groups["name"].Value, match.Groups["type"].Value, id);
    }

    static string MemberText(PayloadKind kind, PayloadMemberContract member)
    {
        if (kind == PayloadKind.Enum)
        {
            return $"  {member.Name} = {member.Type}";
        }

        var id = member.Id is null ? string.Empty : $"[Id({member.Id.Value.ToString(CultureInfo.InvariantCulture)})] ";
        return $"  {id}{member.Name}: {member.Type}";
    }
}
