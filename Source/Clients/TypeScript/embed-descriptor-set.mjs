// Embeds the canonical descriptor set into the package as base64.
//
// Every Chronicle client hands the kernel the descriptor set its contracts package was built with, so the kernel can
// own the one compatibility check rather than each language reimplementing it. ts-proto keeps no descriptors at
// runtime, so the set cannot be rebuilt from the generated code - it has to travel with the package.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../Kernel/Protobuf/chronicle.desc');
const target = path.resolve(here, 'generated/descriptorSet.ts');

const descriptorSet = await fs.readFile(source);

await fs.writeFile(target, `// Copyright (c) Cratis. All rights reserved.
// Licensed under the MIT license. See LICENSE file in the project root for full license information.

// Generated by embed-descriptor-set.mjs from Source/Kernel/Protobuf/chronicle.desc. Do not edit.

const encoded =
    '${descriptorSet.toString('base64')}';

/**
 * The serialized FileDescriptorSet describing every contract in this version of Chronicle.
 *
 * Send this to the kernel on connect and it will tell you whether it still serves them.
 */
export const chronicleDescriptorSet: Uint8Array = Uint8Array.from(atob(encoded), _ => _.charCodeAt(0));
`);

console.log(`Embedded ${descriptorSet.length} bytes of descriptor set into ${path.relative(here, target)}`);
