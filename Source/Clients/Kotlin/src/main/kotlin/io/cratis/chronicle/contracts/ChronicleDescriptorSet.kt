package io.cratis.chronicle.contracts

/**
 * The canonical descriptor set describing every contract in this version of Chronicle.
 *
 * A client hands this to the kernel on connect and the kernel answers whether it still serves them. It ships as a
 * build artifact rather than being rebuilt at runtime because the same set has to be byte-identical across all four
 * Chronicle client SDKs, and two of those keep no descriptors at runtime at all.
 */
object ChronicleDescriptorSet {
    private const val RESOURCE = "/chronicle/chronicle.desc"

    /** The serialized `FileDescriptorSet` for this version of the contracts. */
    val bytes: ByteArray by lazy {
        checkNotNull(ChronicleDescriptorSet::class.java.getResourceAsStream(RESOURCE)) {
            "'$RESOURCE' is not on the classpath. It is generated by Source/Kernel/Protobuf/generate-protos.sh " +
                "and embedded by the contracts build."
        }.use { it.readBytes() }
    }

    /** The version of the contracts this package carries - the protocol version it speaks. */
    val protocolVersion: String by lazy {
        ChronicleDescriptorSet::class.java.`package`?.implementationVersion ?: "0.0.0"
    }
}
