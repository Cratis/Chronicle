namespace Cratis.Chronicle.Concepts.Projections.Generations.for_MaterializationGenerationStateExtensions.when_checking_lifecycle_transitions;

public class with_each_state_pair : Specification
{
    [Theory]
    [InlineData(MaterializationGenerationState.Building, MaterializationGenerationState.Building, false)]
    [InlineData(MaterializationGenerationState.Building, MaterializationGenerationState.Following, true)]
    [InlineData(MaterializationGenerationState.Building, MaterializationGenerationState.Active, false)]
    [InlineData(MaterializationGenerationState.Building, MaterializationGenerationState.Retired, false)]
    [InlineData(MaterializationGenerationState.Building, MaterializationGenerationState.Archived, false)]
    [InlineData(MaterializationGenerationState.Building, MaterializationGenerationState.Abandoned, true)]
    [InlineData(MaterializationGenerationState.Building, MaterializationGenerationState.Removed, false)]
    [InlineData(MaterializationGenerationState.Following, MaterializationGenerationState.Building, false)]
    [InlineData(MaterializationGenerationState.Following, MaterializationGenerationState.Following, false)]
    [InlineData(MaterializationGenerationState.Following, MaterializationGenerationState.Active, true)]
    [InlineData(MaterializationGenerationState.Following, MaterializationGenerationState.Retired, false)]
    [InlineData(MaterializationGenerationState.Following, MaterializationGenerationState.Archived, false)]
    [InlineData(MaterializationGenerationState.Following, MaterializationGenerationState.Abandoned, true)]
    [InlineData(MaterializationGenerationState.Following, MaterializationGenerationState.Removed, false)]
    [InlineData(MaterializationGenerationState.Active, MaterializationGenerationState.Building, false)]
    [InlineData(MaterializationGenerationState.Active, MaterializationGenerationState.Following, false)]
    [InlineData(MaterializationGenerationState.Active, MaterializationGenerationState.Active, false)]
    [InlineData(MaterializationGenerationState.Active, MaterializationGenerationState.Retired, true)]
    [InlineData(MaterializationGenerationState.Active, MaterializationGenerationState.Archived, false)]
    [InlineData(MaterializationGenerationState.Active, MaterializationGenerationState.Abandoned, false)]
    [InlineData(MaterializationGenerationState.Active, MaterializationGenerationState.Removed, false)]
    [InlineData(MaterializationGenerationState.Retired, MaterializationGenerationState.Building, false)]
    [InlineData(MaterializationGenerationState.Retired, MaterializationGenerationState.Following, false)]
    [InlineData(MaterializationGenerationState.Retired, MaterializationGenerationState.Active, true)]
    [InlineData(MaterializationGenerationState.Retired, MaterializationGenerationState.Retired, false)]
    [InlineData(MaterializationGenerationState.Retired, MaterializationGenerationState.Archived, true)]
    [InlineData(MaterializationGenerationState.Retired, MaterializationGenerationState.Abandoned, false)]
    [InlineData(MaterializationGenerationState.Retired, MaterializationGenerationState.Removed, true)]
    [InlineData(MaterializationGenerationState.Archived, MaterializationGenerationState.Building, false)]
    [InlineData(MaterializationGenerationState.Archived, MaterializationGenerationState.Following, false)]
    [InlineData(MaterializationGenerationState.Archived, MaterializationGenerationState.Active, false)]
    [InlineData(MaterializationGenerationState.Archived, MaterializationGenerationState.Retired, false)]
    [InlineData(MaterializationGenerationState.Archived, MaterializationGenerationState.Archived, false)]
    [InlineData(MaterializationGenerationState.Archived, MaterializationGenerationState.Abandoned, false)]
    [InlineData(MaterializationGenerationState.Archived, MaterializationGenerationState.Removed, true)]
    [InlineData(MaterializationGenerationState.Abandoned, MaterializationGenerationState.Building, false)]
    [InlineData(MaterializationGenerationState.Abandoned, MaterializationGenerationState.Following, false)]
    [InlineData(MaterializationGenerationState.Abandoned, MaterializationGenerationState.Active, false)]
    [InlineData(MaterializationGenerationState.Abandoned, MaterializationGenerationState.Retired, false)]
    [InlineData(MaterializationGenerationState.Abandoned, MaterializationGenerationState.Archived, false)]
    [InlineData(MaterializationGenerationState.Abandoned, MaterializationGenerationState.Abandoned, false)]
    [InlineData(MaterializationGenerationState.Abandoned, MaterializationGenerationState.Removed, true)]
    [InlineData(MaterializationGenerationState.Removed, MaterializationGenerationState.Building, false)]
    [InlineData(MaterializationGenerationState.Removed, MaterializationGenerationState.Following, false)]
    [InlineData(MaterializationGenerationState.Removed, MaterializationGenerationState.Active, false)]
    [InlineData(MaterializationGenerationState.Removed, MaterializationGenerationState.Retired, false)]
    [InlineData(MaterializationGenerationState.Removed, MaterializationGenerationState.Archived, false)]
    [InlineData(MaterializationGenerationState.Removed, MaterializationGenerationState.Abandoned, false)]
    [InlineData(MaterializationGenerationState.Removed, MaterializationGenerationState.Removed, false)]
    public void should_preserve_the_lifecycle(MaterializationGenerationState from, MaterializationGenerationState to, bool expected) =>
        from.CanTransitionTo(to).ShouldEqual(expected);
}
