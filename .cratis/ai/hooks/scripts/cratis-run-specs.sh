# Read-only MSBuild evaluation followed by built runners. Children inherit the gate's process group.
exec node --input-type=module - "$@" <<'NODE'
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

function refuse(message) {
    console.error(`cratis-run-specs: ${message}`);
    process.exit(1);
}

const { values } = parseArgs({ args: process.argv.slice(2), options: {
    project: { type: 'string' }, solution: { type: 'string' }, configuration: { type: 'string', default: 'Debug' },
    framework: { type: 'string' }, 'no-build': { type: 'boolean' },
} });
if (!values['no-build']) refuse('--no-build is required; restore and build once before running specs.');
if (values.project && values.solution) refuse('Select either --project or --solution, not both.');

function dotnet(arguments_) {
    const result = spawnSync('dotnet', arguments_, { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
    if (result.error || result.status !== 0) refuse(`Metadata evaluation failed: dotnet ${arguments_.join(' ')}\n${result.error?.message ?? result.stderr}`);
    return result.stdout;
}

const properties = 'IsTestProject,IsTestingPlatformApplication,UseMicrosoftTestingPlatformRunner,OutputType,TargetPath,TargetFramework,TargetFrameworks,AssemblyName,XunitAutoGeneratedEntryPoint';
function evaluate(project, framework) {
    const arguments_ = ['msbuild', project, '-nologo', `-p:Configuration=${values.configuration}`];
    if (framework) arguments_.push(`-p:TargetFramework=${framework}`);
    arguments_.push(`-getProperty:${properties}`, '-getItem:PackageReference');
    try {
        const metadata = JSON.parse(dotnet(arguments_));
        if (!metadata.Properties || !Array.isArray(metadata.Items?.PackageReference)) throw new Error('Missing evaluated Properties or PackageReference items');
        return metadata;
    } catch (error) {
        refuse(`Cannot evaluate ${project}: ${error.message}. Restore/build the matching configuration first; configure a repository-owned gate override for unsupported projects.`);
    }
}

let projects;
if (values.project) projects = [resolve(values.project)];
else {
    const solutions = values.solution ? [values.solution] : readdirSync('.').filter(name => /\.slnx?$/.test(name));
    if (solutions.length !== 1) refuse('Expected one solution in the working directory; select --solution or --project explicitly in a gate override.');
    const solution = resolve(solutions[0]);
    // Ignore localized headings; accept only actual project entries, relative to the selected solution.
    projects = dotnet(['sln', solution, 'list']).split(/\r?\n/).map(line => line.trim())
        .filter(line => /\.(?:cs|fs|vb)proj$/i.test(line)).map(line => resolve(dirname(solution), line.replaceAll('\\', '/')));
    if (!projects.length) refuse(`No project entries could be established for ${solution}; no specifications verified.`);
}

function classify(metadata, project) {
    const properties = metadata.Properties;
    const packages = new Set(metadata.Items.PackageReference.map(item => String(item.Identity).toLowerCase()));
    const platform = properties.IsTestingPlatformApplication?.toLowerCase() === 'true';
    const xunit = ['xunit.v3', 'xunit.v3.core', 'xunit.v3.mtp-off', 'xunit.v3.core.mtp-off',
        'xunit.v3.mtp-v1', 'xunit.v3.core.mtp-v1', 'xunit.v3.mtp-v2', 'xunit.v3.core.mtp-v2']
        .some(name => packages.has(name));
    const native = packages.has('cratis.specifications.runner');
    const tunit = packages.has('tunit');
    const legacy = ['xunit', 'nunit', 'mstest.testframework'].some(name => packages.has(name));
    const test = properties.IsTestProject?.toLowerCase() === 'true' || platform || xunit || native || tunit || legacy;
    if (!test) return 'non-test';
    if (properties.XunitAutoGeneratedEntryPoint?.toLowerCase() === 'false') refuse(`${project}: custom application entrypoint; configure a repository-owned spec invocation override (do not start the server).`);
    if (['exe', 'winexe'].includes(properties.OutputType?.toLowerCase())) {
        if (xunit && (packages.has('xunit.v3.mtp-off') || packages.has('xunit.v3.core.mtp-off')
            || properties.UseMicrosoftTestingPlatformRunner?.toLowerCase() !== 'true')) return 'xunit-mtp-off';
        if (platform || xunit || native || tunit) return 'mtp';
    }
    // Test.Sdk can generate an Exe entrypoint for legacy VSTest projects too.
    if (properties.IsTestProject?.toLowerCase() === 'true' && !platform && !xunit && !native && !tunit && legacy && packages.has('microsoft.net.test.sdk')) return 'vstest';
    refuse(`${project}: unsupported/unknown test runner; configure a repository-owned backend-specs override instead of falling back to dotnet test.`);
}

let reportRoot;
function reportPath() {
    if (!reportRoot) {
        const repository = spawnSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' });
        const root = repository.status === 0 ? repository.stdout.trim() : process.cwd();
        const artifacts = join(root, '.ai-work', 'spec-runs');
        mkdirSync(artifacts, { recursive: true });
        reportRoot = mkdtempSync(join(artifacts, 'run-'));
    }
    return join(reportRoot, `${executed}.trx`);
}

function verifyCounts(runner, output, report, project) {
    let total;
    let passed;
    let failed;
    let skipped;
    if (runner === 'xunit-mtp-off' && existsSync(report)) {
        const counters = /<(?:\w+:)?Counters\b([^>]*)\/?\s*>/.exec(readFileSync(report, 'utf8'))?.[1];
        const count = name => { const value = new RegExp(`\\b${name}="(\\d+)"`).exec(counters ?? ''); return value ? Number(value[1]) : undefined; };
        total = count('total'); passed = count('passed'); failed = count('failed'); skipped = count('notExecuted') ?? 0;
    } else if (runner !== 'xunit-mtp-off') {
        const count = expression => { const match = expression.exec(output); return match ? Number(match[1]) : undefined; };
        total = count(/\btotal:\s*(\d+)/i);
        passed = count(/\b(?:succeeded|passed):\s*(\d+)/i);
        failed = count(/\bfailed:\s*(\d+)/i);
        skipped = count(/\bskipped:\s*(\d+)/i) ?? 0;
    }
    if (total === 0) refuse(`${project}: zero tests executed; no specifications verified.`);
    if (total === undefined || passed === undefined || failed === undefined) refuse(`${project}: UNVERIFIED — runner count evidence unavailable. Configure a repository-owned invocation with verified reports.`);
    if (failed !== 0 || passed + skipped !== total || passed === 0) refuse(`${project}: not all specifications passed (total=${total}, passed=${passed}, failed=${failed}).`);
    console.log(`cratis-run-specs: verified total=${total}, passed=${passed}, failed=${failed}`);
}

let executed = 0;
for (const project of projects) {
    if (!existsSync(project)) refuse(`Solution project does not exist: ${project}`);
    const initial = evaluate(project);
    const frameworks = (initial.Properties.TargetFrameworks || initial.Properties.TargetFramework || '').split(';').filter(Boolean);
    const runner = classify(initial, project);
    if (runner === 'non-test') { console.log(`cratis-run-specs: SKIP non-test ${project}`); continue; }
    if (!frameworks.length) refuse(`${project}: target framework unavailable; evaluate the restored project or supply an override.`);
    if (values.framework && !frameworks.includes(values.framework)) refuse(`${project}: requested framework ${values.framework} not in ${frameworks.join(', ')}.`);
    for (const framework of values.framework ? [values.framework] : frameworks) {
        const metadata = initial.Properties.TargetFrameworks ? evaluate(project, framework) : initial;
        const selectedRunner = classify(metadata, project);
        if (selectedRunner === 'non-test') refuse(`${project} (${framework}): inconsistent test metadata; no suite may be omitted.`);
        const target = metadata.Properties.TargetPath;
        if (!target || !isAbsolute(target)) refuse(`${project}: evaluated TargetPath unavailable; perform the matching ${values.configuration}/${framework} build first.`);
        const apphost = target.replace(/\.dll$/i, process.platform === 'win32' ? '.exe' : '');
        const useApphost = apphost !== target && existsSync(apphost);
        if (!useApphost && !existsSync(target)) refuse(`${project}: missing built output ${target}; perform the matching ${values.configuration}/${framework} build first.`);
        const report = selectedRunner === 'xunit-mtp-off' ? reportPath() : undefined;
        const command = selectedRunner === 'vstest' || !useApphost ? 'dotnet' : apphost;
        const arguments_ = selectedRunner === 'vstest'
            ? ['test', project, '--configuration', values.configuration, '--no-build', '--framework', framework]
            : [...(useApphost ? [] : [target]), ...(report ? ['-trx', report] : [])];
        console.log(`cratis-run-specs: RUN ${project} runner=${selectedRunner} framework=${framework} configuration=${values.configuration}`);
        const result = spawnSync(command, arguments_, { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
        process.stdout.write(result.stdout ?? '');
        process.stderr.write(result.stderr ?? '');
        if (result.error) refuse(`${project}: ${result.error.message}`);
        if (result.status !== 0) process.exit(result.status ?? 1);
        verifyCounts(selectedRunner, (result.stdout ?? '') + (result.stderr ?? ''), report, project);
        executed++;
    }
}
console.log(executed ? `cratis-run-specs: verified ${executed} project/framework suite(s).` : 'cratis-run-specs: NO-OP — no test projects; no specifications verified.');
NODE
